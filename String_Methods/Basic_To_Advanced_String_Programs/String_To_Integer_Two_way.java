class String_To_Integer_Two_way{
    public static void main(String[] args) {
        
        String str1="123";
        System.out.println(Integer.parseInt(str1));
        System.out.println(Integer.valueOf(str1));
        
        

        String str2="A";
        int s=(int)str2.charAt(0);
        System.out.println(s);





    }
}