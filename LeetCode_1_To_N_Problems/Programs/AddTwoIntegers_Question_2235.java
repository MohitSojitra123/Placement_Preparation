public class AddTwoIntegers_Question_2235 {

    public static void main(String[] args) {

        int num1 = 12;
        int num2 = 5;


        int result = sum(num1, num2);


        System.out.println("Sum = " + result);
    }


    public static int sum(int num1, int num2) {

        return num1 + num2;
    }
}